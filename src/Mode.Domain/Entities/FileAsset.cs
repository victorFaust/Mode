namespace Mode.Domain.Entities;

/// <summary>A named file in one channel or conversation; same-name uploads add a <see cref="FileVersion"/>.</summary>
public class FileAsset
{
    public Guid Id { get; set; }
    public Guid? ChannelId { get; set; }
    public Guid? ConversationId { get; set; }
    public required string Name { get; set; }
    public required string NormalizedName { get; set; }
    public int CurrentVersionNo { get; set; }
    public required string CreatedByUserId { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }
    public string? DeletedByUserId { get; set; }

    public Channel? Channel { get; set; }
    public Conversation? Conversation { get; set; }
    public List<FileVersion> Versions { get; set; } = [];
}

public class FileVersion
{
    public Guid Id { get; set; }
    public Guid FileAssetId { get; set; }
    public int VersionNo { get; set; }

    /// <summary>Storage key of the original bytes; generated by Mode, never derived from the file name.</summary>
    public required string ObjectKey { get; set; }

    public long SizeBytes { get; set; }
    public required string ContentType { get; set; }

    /// <summary>Computed while scanning.</summary>
    public string? Sha256 { get; set; }

    public ScanStatus ScanStatus { get; set; }

    /// <summary>Virus name, or why the file was blocked.</summary>
    public string? ScanDetail { get; set; }

    public DateTimeOffset? ScannedAt { get; set; }
    public PreviewStatus PreviewStatus { get; set; }
    public string? ThumbnailKey { get; set; }
    public string? PreviewKey { get; set; }
    public string? ExtractedText { get; set; }
    public required string UploadedByUserId { get; set; }
    public DateTimeOffset UploadedAt { get; set; }

    public FileAsset? FileAsset { get; set; }
}

/// <summary>An upload in progress: created when a signed upload link is handed out, completed into a <see cref="FileVersion"/>.</summary>
public class UploadSession
{
    public Guid Id { get; set; }
    public required string UserId { get; set; }
    public Guid? ChannelId { get; set; }
    public Guid? ConversationId { get; set; }
    public required string FileName { get; set; }
    public required string NormalizedName { get; set; }
    public long DeclaredSize { get; set; }
    public required string ContentType { get; set; }
    public required string StorageKey { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset ExpiresAt { get; set; }
    public DateTimeOffset? ReceivedAt { get; set; }
    public DateTimeOffset? CompletedAt { get; set; }
}

public class MessageAttachment
{
    public Guid MessageId { get; set; }
    public Guid FileAssetId { get; set; }

    /// <summary>Version current when the file was attached.</summary>
    public int VersionNo { get; set; }

    public FileAsset? FileAsset { get; set; }
}

/// <summary>PostgreSQL-backed background job; claimed with FOR UPDATE SKIP LOCKED.</summary>
public class Job
{
    public long Id { get; set; }
    public required string Type { get; set; }
    public required string PayloadJson { get; set; }
    public JobStatus Status { get; set; }
    public int Attempts { get; set; }
    public int MaxAttempts { get; set; }
    public DateTimeOffset RunAfter { get; set; }
    public DateTimeOffset? LockedUntil { get; set; }
    public string? LastError { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? CompletedAt { get; set; }
}
